import type { Loan, ManagerProfile } from '../types/loan'
import { buildLoan, type LoanInput } from '../utils/loanFactory'
import { rupees } from './costModel'

type RupeeInput = Omit<
  LoanInput,
  'originalAmount' | 'outstandingBalance' | 'interestIncome' | 'feeIncome' | 'averageOutstandingBalance'
> & {
  originalAmount: number
  outstandingBalance: number
  interestIncome: number
  feeIncome: number
  averageOutstandingBalance: number
}

/** Author mock records in rupees for readability; convert to integer paise once, here. */
function mockLoan(r: RupeeInput): Loan {
  return buildLoan({
    ...r,
    originalAmount: rupees(r.originalAmount),
    outstandingBalance: rupees(r.outstandingBalance),
    interestIncome: rupees(r.interestIncome),
    feeIncome: rupees(r.feeIncome),
    averageOutstandingBalance: rupees(r.averageOutstandingBalance),
  })
}

