import { Eraser, MessageSquarePlus, RefreshCw, Send, Sparkles, Trash2, TriangleAlert } from 'lucide-react'
import { useEffect, useRef, useState, type FormEvent, type KeyboardEvent } from 'react'
import { Link, useSearchParams } from 'react-router-dom'
import { AiEvidenceCard } from '../components/AiEvidenceCard'
import { AiExplanationCard } from '../components/AiExplanationCard'
import { env } from '../config/env'
import { useAiChat } from '../context/AiChatContext'
import { useAppData } from '../context/AppDataContext'
import { useApi } from '../hooks/useApi'
import { fetchAiStatus } from '../services/aiService'
import { keys } from '../services/keys'
import { listLoans } from '../services/loanService'
import type { AiMessage } from '../types/ai'
import { periodRangeLabel } from '../utils/profitability'

/** Demonstration mode: the scripted responder understands these. */
const MOCK_QUESTIONS = [
  'Why is Rahul’s loan showing negative contribution?',
  'What is the biggest expense in this loan?',
  'Why has the expected credit loss increased?',
  'Compare Rahul’s loan with Aman’s loan.',
  'Which loans have negative estimated contributions?',
  'Which loan products have the highest average contribution?',
]

/** Backend mode: questions about the ONE loan in focus (the backend explains a single loan for a reporting period). */
const LOAN_QUESTIONS = [
  'Why is this loan showing a negative contribution?',
  'What is the largest cost for this loan?',
  'Why did ECL increase?',
  'What if funding costs increased?',
  'Which factors are reducing contribution?',
  'Why is this loan more profitable than another loan?',
  'Explain this in simple language.',
]
const SUGGESTED_QUESTIONS = env.useMock ? MOCK_QUESTIONS : LOAN_QUESTIONS

const MAX_LENGTH = 500

function TypingIndicator() {
  return (
    <div role="status" aria-live="polite" className="flex items-start gap-3">
      <Avatar />
      <div className="rounded-2xl rounded-tl-sm border border-line bg-white px-4 py-3 shadow-sm">
        <span className="sr-only">LoanLens AI is preparing an answer…</span>
        <span className="flex items-center gap-1.5" aria-hidden="true">
          {[0, 150, 300].map((delay) => (
            <span key={delay} className="size-2 animate-bounce rounded-full bg-slate-400" style={{ animationDelay: `${delay}ms` }} />
          ))}
        </span>
      </div>
    </div>
  )
}

function Avatar() {
  return (
    <span className="flex size-8 shrink-0 items-center justify-center rounded-full bg-primary text-white">
      <Sparkles className="size-4" aria-hidden="true" />
    </span>
  )
}

function SourceNote({ message }: { message: AiMessage }) {
  if (message.source === 'fallback') {
    return <p className="mt-3 text-xs text-muted">Deterministic explanation — no AI model was used.</p>
  }
  if (message.source === 'demo-scripted') {
    return (
      <p className="mt-3 flex items-start gap-1.5 text-xs text-warning">
        <TriangleAlert className="mt-px size-3.5 shrink-0" aria-hidden="true" />
        Demonstration response: scripted from the loan records. It was not generated by an AI model.
      </p>
    )
  }
  return (
    <p className="mt-3 text-xs text-muted">
      AI-generated explanation{message.model ? ` · ${message.model}` : ''} · figures supplied by the LoanLens backend
    </p>
  )
}

function AssistantMessage({ message, onRetry, retryDisabled, loanNames }: { message: AiMessage; onRetry: (id: string) => void; retryDisabled: boolean; loanNames: Map<string, string> }) {
  if (message.error) {
    return (
      <div className="flex items-start gap-3">
        <Avatar />
        <div role="alert" className="max-w-[44rem] rounded-2xl rounded-tl-sm border border-negative/30 bg-negative/5 px-4 py-3 text-sm">
          <p className="font-semibold text-negative">I couldn’t get an answer</p>
          <p className="mt-1 text-ink">{message.error.message}</p>
          <button type="button" onClick={() => onRetry(message.id)} disabled={retryDisabled} className="btn-secondary mt-3 px-3 py-1.5">
            <RefreshCw className="size-3.5" aria-hidden="true" />
            Retry
          </button>
        </div>
      </div>
    )
  }

  if (message.explanation) {
    return (
      <div className="flex items-start gap-3">
        <Avatar />
        <div className="min-w-0 max-w-[48rem] flex-1 rounded-2xl rounded-tl-sm border border-line bg-white px-4 py-3.5 shadow-sm">
          <AiExplanationCard explanation={message.explanation} />
        </div>
      </div>
    )
  }

  const shownInCards = new Set(message.evidence?.flatMap((e) => [e.loanId, ...e.items.map((i) => i.loanId)]).filter(Boolean))
  const extraLoans = (message.relatedLoanIds ?? []).filter((id) => !shownInCards.has(id))

  return (
    <div className="flex items-start gap-3">
      <Avatar />
      <div className="min-w-0 max-w-[44rem] flex-1 rounded-2xl rounded-tl-sm border border-line bg-white px-4 py-3.5 shadow-sm">
        <div className="space-y-3 text-sm leading-relaxed text-ink">
          {message.text.split('\n\n').map((paragraph, i) => (
            <p key={i}>{paragraph}</p>
          ))}
        </div>

        {message.evidence && message.evidence.length > 0 && (
          <div className="mt-4 space-y-3">
            <p className="text-xs font-semibold uppercase tracking-wide text-muted">Supporting figures</p>
            {message.evidence.map((e, i) => (
              <AiEvidenceCard key={`${e.title}-${i}`} evidence={e} />
            ))}
          </div>
        )}

        {extraLoans.length > 0 && (
          <p className="mt-3 flex flex-wrap items-center gap-2 text-xs text-muted">
            Open loan:
            {extraLoans.map((id) => (
              <Link key={id} to={`/loans/${id}`} className="rounded-full border border-line bg-slate-50 px-2.5 py-1 font-semibold text-primary hover:border-primary/40">
                {loanNames.get(id) ?? id}
              </Link>
            ))}
          </p>
        )}
        <SourceNote message={message} />
      </div>
    </div>
  )
}

export default function AiInsights() {
  const { conversations, active, activeId, pending, ask, retry, newConversation, clearConversation, clearHistory, select, setFocusLoan, setCompareLoan } = useAiChat()
  const { period } = useAppData()
  const [params, setParams] = useSearchParams()
  const [draft, setDraft] = useState('')
  const scroller = useRef<HTMLDivElement>(null)

  // The loan list only feeds the "loan in focus" picker. If it fails the chat still works portfolio-wide.
  const loansQuery = useApi(keys.loans(period.id), () => listLoans(period.id))
  const loans = loansQuery.data ?? []
  const loanNames = new Map(loans.map((l) => [l.id, l.customerName]))

  // Backend mode: is a real AI provider configured on the server? (No secret is ever returned.)
  const statusQuery = useApi(keys.aiStatus(), fetchAiStatus)
  const status = statusQuery.data
  // The backend explains ONE loan for a reporting period, so a loan must be chosen first.
  const needsLoan = !env.useMock && !active.loanId
  const canAsk = env.aiEnabled && !needsLoan

  // /ai-insights?loan=L1001 (from the loan page) pre-selects the loan in focus.
  const loanParam = params.get('loan')
  useEffect(() => {
    if (loanParam) {
      setFocusLoan(loanParam)
      setParams({}, { replace: true })
    }
  }, [loanParam, setFocusLoan, setParams])

  useEffect(() => {
    scroller.current?.scrollTo({ top: scroller.current.scrollHeight, behavior: 'smooth' })
  }, [active.messages.length, pending, activeId])

  const submit = (text: string) => {
    const question = text.trim()
    if (!question || pending || !canAsk) return
    ask(question)
    setDraft('')
  }
  const onSubmit = (event: FormEvent) => {
    event.preventDefault()
    submit(draft)
  }
  const onKeyDown = (event: KeyboardEvent<HTMLTextAreaElement>) => {
    if (event.key === 'Enter' && !event.shiftKey) {
      event.preventDefault()
      submit(draft)
    }
  }

  const empty = active.messages.length === 0

  return (
    <div className="flex flex-col gap-4 lg:flex-row lg:gap-6">
      {/* Conversation history (desktop) */}
      <aside aria-label="Conversation history" className="hidden w-64 shrink-0 lg:block">
        <button type="button" onClick={newConversation} className="btn-primary w-full">
          <MessageSquarePlus className="size-4" aria-hidden="true" />
          New conversation
        </button>
        <h2 className="mb-2 mt-5 px-1 text-xs font-semibold uppercase tracking-wide text-muted">This session</h2>
        <ul className="space-y-1">
          {conversations.map((c) => (
            <li key={c.id}>
              <button
                type="button"
                onClick={() => select(c.id)}
                aria-current={c.id === activeId ? 'true' : undefined}
                className={`w-full truncate rounded-lg px-3 py-2 text-left text-sm transition ${c.id === activeId ? 'bg-primary/10 font-semibold text-primary' : 'text-ink hover:bg-slate-100'}`}
              >
                {c.title}
              </button>
            </li>
          ))}
        </ul>
        <button type="button" onClick={clearHistory} disabled={pending} className="btn-secondary mt-4 w-full px-3 py-2 text-xs">
          <Trash2 className="size-3.5" aria-hidden="true" />
          Clear all history
        </button>
        <p className="mt-4 px-1 text-xs leading-relaxed text-muted">Conversations are kept in memory for this session only and are not saved in your browser.</p>
      </aside>

      <section aria-label="LoanLens AI" className="card flex min-h-[34rem] min-w-0 flex-1 flex-col overflow-hidden lg:h-[calc(100dvh-8.5rem)]">
        {/* Header */}
        <header className="flex flex-wrap items-center gap-3 border-b border-line px-4 py-3 sm:px-5">
          <span className="flex size-10 items-center justify-center rounded-xl bg-primary text-white">
            <Sparkles className="size-5" aria-hidden="true" />
          </span>
          <div className="min-w-[13rem] flex-1">
            <h1 className="text-base font-bold leading-tight text-ink">LoanLens AI</h1>
            <p className="text-xs text-muted">Explains loan profitability using your loan records · {periodRangeLabel(period)}</p>
          </div>
          <span
            data-testid="ai-mode-badge"
            className={`rounded-full px-2.5 py-1 text-xs font-semibold ring-1 ring-inset ${
              env.useMock
                ? 'bg-warning/10 text-warning ring-warning/30'
                : !env.aiEnabled
                  ? 'bg-slate-100 text-muted ring-slate-200'
                  : status?.providerConfigured
                    ? 'bg-primary/10 text-primary ring-primary/20'
                    : 'bg-slate-100 text-ink ring-slate-300'
            }`}
          >
            {env.useMock
              ? 'Demonstration mode · not an AI model'
              : !env.aiEnabled
                ? 'Switched off'
                : !status
                  ? statusQuery.error
                    ? 'AI status unavailable'
                    : 'Checking AI service…'
                  : status.providerConfigured
                    ? `AI model${status.model ? ` · ${status.model}` : ''}`
                    : 'No AI model configured · backend explanations'}
          </span>
          {active.messages.length > 0 && (
            <button type="button" onClick={clearConversation} disabled={pending} className="btn-secondary px-3 py-1.5 text-xs">
              <Eraser className="size-3.5" aria-hidden="true" />
              Clear conversation
            </button>
          )}
          <div className="flex w-full items-center gap-2 lg:hidden">
            <label htmlFor="ai-conversation" className="sr-only">
              Conversation
            </label>
            <select id="ai-conversation" value={activeId} onChange={(e) => select(e.target.value)} className="input min-w-0 flex-1 py-2">
              {conversations.map((c) => (
                <option key={c.id} value={c.id}>
                  {c.title}
                </option>
              ))}
            </select>
            <button type="button" onClick={newConversation} className="btn-secondary shrink-0 px-3 py-2" aria-label="New conversation">
              <MessageSquarePlus className="size-4" aria-hidden="true" />
              New
            </button>
          </div>
        </header>

        {/* Loan in focus */}
        <div className="flex flex-wrap items-center gap-3 border-b border-line bg-slate-50/60 px-4 py-2.5 text-sm sm:px-5">
          <label htmlFor="ai-focus" className="font-medium text-muted">
            Loan in focus
          </label>
          <select
            id="ai-focus"
            value={active.loanId ?? ''}
            onChange={(e) => setFocusLoan(e.target.value || undefined)}
            className="input w-auto max-w-full py-1.5"
          >
            <option value="">{env.useMock ? 'Whole portfolio' : 'Select a loan…'}</option>
            {active.loanId && !loanNames.has(active.loanId) && <option value={active.loanId}>{active.loanId}</option>}
            {loans.map((l) => (
              <option key={l.id} value={l.id}>
                {l.customerName} · {l.id}
              </option>
            ))}
          </select>
          {active.loanId && (
            <Link to={`/loans/${active.loanId}`} className="text-xs font-semibold text-primary hover:underline">
              View loan
            </Link>
          )}
          {!env.useMock && (
            <>
              <label htmlFor="ai-compare" className="ml-2 font-medium text-muted">
                Compare with <span className="font-normal">(optional)</span>
              </label>
              <select
                id="ai-compare"
                value={active.compareLoanId ?? ''}
                onChange={(e) => setCompareLoan(e.target.value || undefined)}
                className="input w-auto max-w-full py-1.5"
              >
                <option value="">No comparison</option>
                {loans
                  .filter((l) => l.id !== active.loanId)
                  .map((l) => (
                    <option key={l.id} value={l.id}>
                      {l.customerName} · {l.id}
                    </option>
                  ))}
              </select>
            </>
          )}
        </div>

        {!env.aiEnabled && (
          <div role="status" className="flex items-start gap-3 border-b border-warning/30 bg-warning/5 px-4 py-3 text-sm text-ink sm:px-5">
            <TriangleAlert className="mt-0.5 size-4 shrink-0 text-warning" aria-hidden="true" />
            <p>
              <strong>AI Insights is switched off in this build.</strong> It was disabled with <code className="rounded bg-white px-1">VITE_AI_ENABLED=false</code>,
              so no questions can be asked and no answers are made up.
            </p>
          </div>
        )}
        {env.aiEnabled && !env.useMock && status && !status.providerConfigured && (
          <div role="status" data-testid="ai-not-configured" className="flex items-start gap-3 border-b border-line bg-slate-50 px-4 py-3 text-sm text-ink sm:px-5">
            <TriangleAlert className="mt-0.5 size-4 shrink-0 text-warning" aria-hidden="true" />
            <p>
              <strong>No AI model is configured on the server.</strong> Everything still works: questions are answered by fixed backend rules from the
              calculated figures, and each answer says so. To enable AI-written explanations, start the backend with an <code className="rounded bg-white px-1">AI_API_KEY</code>.
            </p>
          </div>
        )}
        {env.aiEnabled && !env.useMock && Boolean(statusQuery.error) && (
          <div role="status" className="flex items-start gap-3 border-b border-warning/30 bg-warning/5 px-4 py-3 text-sm text-ink sm:px-5">
            <TriangleAlert className="mt-0.5 size-4 shrink-0 text-warning" aria-hidden="true" />
            <p>Could not check the AI service status. You can still ask a question; the answer will say how it was produced.</p>
          </div>
        )}

        {/* Messages */}
        <div ref={scroller} className="min-h-0 flex-1 space-y-5 overflow-y-auto px-4 py-5 sm:px-5" aria-live="off">
          {empty ? (
            <div className="mx-auto flex max-w-2xl flex-col items-center py-6 text-center">
              <span className="flex size-14 items-center justify-center rounded-2xl bg-primary/10 text-primary">
                <Sparkles className="size-7" aria-hidden="true" />
              </span>
              <h2 className="mt-4 text-lg font-semibold text-ink">{env.useMock ? 'Ask about a loan or the portfolio' : 'Ask about a loan'}</h2>
              <p className="mt-1 text-sm text-muted">
                {env.useMock
                  ? 'Every explanation comes with the figures behind it, and expected credit loss is always described as an estimate, never a confirmed loss.'
                  : needsLoan
                    ? 'Select a loan above first. LoanLens explains one loan for the reporting period shown in the top bar.'
                    : 'Every explanation shows the figures LoanLens calculated, says whether an AI model or fixed backend rules wrote the wording, and describes expected credit loss as an estimate, never a confirmed loss.'}
              </p>
              <ul className="mt-6 grid w-full gap-2 text-left sm:grid-cols-2">
                {SUGGESTED_QUESTIONS.map((q) => (
                  <li key={q}>
                    <button
                      type="button"
                      onClick={() => submit(q)}
                      disabled={pending || !canAsk}
                      className="h-full w-full rounded-xl border border-line bg-white px-4 py-3 text-sm text-ink shadow-sm transition hover:border-primary/40 hover:bg-primary/5 disabled:opacity-60"
                    >
                      {q}
                    </button>
                  </li>
                ))}
              </ul>
            </div>
          ) : (
            active.messages.map((m) =>
              m.role === 'user' ? (
                <div key={m.id} className="flex justify-end">
                  <p className="max-w-[85%] whitespace-pre-wrap rounded-2xl rounded-tr-sm bg-primary px-4 py-2.5 text-sm text-white shadow-sm">{m.text}</p>
                </div>
              ) : (
                <AssistantMessage key={m.id} message={m} onRetry={retry} retryDisabled={pending} loanNames={loanNames} />
              ),
            )
          )}
          {pending && <TypingIndicator />}
        </div>

        {/* Composer */}
        <div className="border-t border-line bg-white px-4 py-3 sm:px-5">
          {!empty && (
            <div className="-mx-1 mb-3 flex gap-2 overflow-x-auto px-1 pb-1" aria-label="Suggested questions">
              {SUGGESTED_QUESTIONS.map((q) => (
                <button
                  key={q}
                  type="button"
                  onClick={() => submit(q)}
                  disabled={pending || !canAsk}
                  className="shrink-0 whitespace-nowrap rounded-full border border-line bg-slate-50 px-3 py-1.5 text-xs text-ink hover:border-primary/40 hover:bg-primary/5 disabled:opacity-60"
                >
                  {q}
                </button>
              ))}
            </div>
          )}
          <form onSubmit={onSubmit} className="flex items-end gap-2">
            <div className="min-w-0 flex-1">
              <label htmlFor="ai-question" className="sr-only">
                Ask LoanLens AI a question
              </label>
              <textarea
                id="ai-question"
                value={draft}
                onChange={(e) => setDraft(e.target.value)}
                onKeyDown={onKeyDown}
                maxLength={MAX_LENGTH}
                disabled={!canAsk}
                rows={2}
                placeholder={
                  needsLoan
                    ? 'Select a loan first…'
                    : active.loanId
                      ? `Ask about ${loanNames.get(active.loanId) ?? active.loanId}’s loan…`
                      : 'Ask about a loan or the portfolio…'
                }
                className="input resize-none"
              />
            </div>
            <button type="submit" disabled={pending || !canAsk || draft.trim().length === 0} className="btn-primary h-11 shrink-0">
              <Send className="size-4" aria-hidden="true" />
              {pending ? 'Analysing…' : 'Send'}
            </button>
          </form>
          <p className="mt-2 text-xs text-muted">Enter to send · Shift+Enter for a new line · {draft.length}/{MAX_LENGTH}</p>
        </div>
      </section>
    </div>
  )
}
